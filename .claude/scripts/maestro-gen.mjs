// ---------------------------------------------------------------- tiện ích
export function fold(s) {
  return String(s ?? '').normalize('NFC').split('')
    .map((c) => c.normalize('NFD').replace(/[̀-ͯ]/g, ''))
    .join('').replace(/đ/g, 'd').replace(/Đ/g, 'D').toLowerCase();
}
const clean = (v) => String(v ?? '').replace(/[ \t]+/g, ' ').trim();
const isDash = (v) => /^[-—–\s]*$/.test(String(v ?? ''));
const q = (s) => JSON.stringify(String(s)); // chuỗi YAML hợp lệ (JSON là tập con YAML)

function parseArgs(argv) {
  const o = { cmd: argv[0], dir: '', tc: '', dryRun: false, root: '', env: '', build: '' };
  for (let i = 1; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--dir') o.dir = argv[++i];
    else if (a === '--tc') o.tc = argv[++i];
    else if (a === '--root') o.root = argv[++i];
    else if (a === '--env') o.env = argv[++i];
    else if (a === '--build') o.build = argv[++i];
    else if (a === '--dry-run') o.dryRun = true;
  }
  return o;
}

// ---------------------------------------------------------------- parse test case
function parseLocal(md) {
  const lines = String(md).replace(/\r\n?/g, '\n').split('\n');
  const blocks = [];
  let cur = [];
  const flush = () => { const b = cur.join('\n'); if (/\*\*STT:\*\*/i.test(b)) blocks.push(b); cur = []; };
  for (const l of lines) { if (/^\s*---\s*$/.test(l)) flush(); else cur.push(l); }
  flush();
  return blocks.map((b) => {
    const tc = { steps: [], parseErrors: [] };
    let step = null; let key = null; let obj = null;
    for (const line of b.split('\n')) {
      const m = line.match(FIELD_RE);
      if (m) {
        const f = m[1].toLowerCase(); const v = m[2] ?? '';
        if (f === 'step') { step = { n: clean(v), action: '', expected: '', testData: '' }; tc.steps.push(step); obj = null; continue; }
        if (['action', 'expected', 'test data'].includes(f)) {
          if (!step) { tc.parseErrors.push(`${m[1]} trước Step`); obj = null; continue; }
          key = f === 'test data' ? 'testData' : f; step[key] = clean(v); obj = step; continue;
        }
        key = f === 'sub-category' ? 'subcategory' : f; tc[key] = clean(v); obj = tc; continue;
      }
      if (obj && key && line.trim()) obj[key] = `${obj[key]}\n${line.trim()}`.trim();
    }
    const chk = String(tc.checklist ?? '').match(CHK_RE);
    tc.chk = chk ? chk[0] : null;
    tc.retired = Boolean(tc.chk && new RegExp(`${tc.chk}\\s*\\(\\s*retired\\s*\\)`, 'i').test(tc.checklist));
    return tc;
  });
}

export function parseTestcases(md) {
  // Core là nguồn parse chuẩn (biết Target/Role/Data); parser cục bộ chỉ khi import core thất bại.
  const list = typeof core.parseTestcasesFile === 'function' ? core.parseTestcasesFile(md) : parseLocal(md);
  return list.map((t) => ({
    ...t,
    chk: t.chk || null,
    target: fold(t.target ?? '').trim(),
    role: clean(t.role ?? ''),
    data: clean(t.data ?? ''),
    steps: (t.steps || []).map((s) => ({
      n: s.n, action: clean(s.action), expected: clean(s.expected), testData: clean(s.testData),
    })),
  }));
}

// ---------------------------------------------------------------- map bước
function quoted(text) {
  const out = [];
  const re = /"([^"\n]+)"|“([^”\n]+)”|'([^'\n]+)'|‘([^’\n]+)’|«([^»\n]+)»/g;
  let m;
  while ((m = re.exec(text))) out.push({ v: m[1] ?? m[2] ?? m[3] ?? m[4] ?? m[5], i: m.index });
  return out;
}
const looksLikeId = (s) => /^[A-Za-z][\w]*([.\-_][\w]+)+$/.test(s) && !/\s/.test(s) && s === s.toLowerCase();
const slugify = (s) => fold(s).replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const clauses = (t) => String(t ?? '').split(/\n|;/).map((x) => x.trim()).filter(Boolean);
const isSlow = (...ts) => /igas|signalr|dang bom|da bom|dang cho bom/.test(fold(ts.join(' ')));

function tapCmd(label) {
  return looksLikeId(label) ? { y: `- tapOn:\n    id: ${q(label)}` } : { y: `- tapOn: ${q(label)}` };
}
function envRef(v) {
  const m = String(v).match(/^ENV:\s*([A-Za-z_][A-Za-z0-9_]*)$/);
  return m ? `\${${m[1]}}` : null;
}

/** Trả { lines:[yaml…], kind } hoặc { skip: 'lý do' } cho 1 mệnh đề Action. */
export function mapAction(text, ctx) {
  const o = clean(text); const n = fold(o);
  const qs = quoted(o);
  if (/\b(mo|khoi dong|chay)\b.*\b(app|ung dung)\b/.test(n)) {
    const clear = /xoa du lieu|clear/.test(n);
    return { kind: 'launch', lines: [`- launchApp:\n    permissions:\n      all: allow${clear ? '\n    clearState: true' : ''}`] };
  }
  if (/\bdang nhap\b/.test(n)) {
    const vm = n.match(/\bvai(?: tro)?\s+(.+)$/);
    let role = ctx.role;
    if (vm) {
      const inQuote = qs[0]?.v;
      role = slugify(inQuote || o.slice(o.length - vm[1].length)) || role;
    }
    if (!role) return { skip: 'đăng nhập nhưng không biết vai (thiếu **Role:** hoặc "vai X")' };
    ctx.loggedIn = true;
    return { kind: 'login', role, lines: [loginYaml(ctx, role)] };
  }
  if (/\bnhap\b/.test(n) && /\bvao\b/.test(n)) {
    if (qs.length < 2) return { skip: 'nhập thiếu giá trị hoặc ô (cần "V" vào "X")' };
    const [val, field] = [qs[0].v, qs[1].v];
    const env = envRef(val);
    if (!env && /mat khau|password|\bpin\b|token/.test(fold(field))) {
      return { skip: `giá trị nhập vào "${field}" là bí mật — phải dùng ENV: VAR` };
    }
    return { kind: 'input', lines: [tapCmd(field).y, `- inputText: ${q(env || val)}`] };
  }
  if (/\bgia lap\b.*\bbom\b/.test(n)) {
    const stage = /da bom/.test(n) && !/dang bom/.test(n) ? 'pumped' : /dang bom/.test(n) && !/da bom/.test(n) ? 'inuse' : 'both';
    return { kind: 'pump', lines: [`- runFlow:\n    file: ${ctx.sub('igas-simulate-pump.yaml')}\n    env:\n      STAGE: ${stage}`] };
  }
  if (/\b(chup|dinh kem|dang tai|tai len)\b.*\banh\b/.test(n)) {
    return { kind: 'media', lines: [
      '# Chọn ảnh từ thư viện của simulator: addMedia nạp ảnh mẫu vào thư viện, bước chọn ảnh trong picker làm tay/bổ sung khi app có nhãn.',
      '- addMedia:\n    - ${QA_PHOTO_PATH}',
    ] };
  }
  if (/\b(vuot|cuon)\b/.test(n)) {
    if (/\b(vuot len|cuon xuong)\b/.test(n)) return { kind: 'scroll', lines: ['- scroll'] };
    if (/\b(vuot xuong|cuon len)\b/.test(n)) return { kind: 'scroll', lines: ['- swipe:\n    direction: DOWN'] };
    return { skip: 'vuốt/cuộn không rõ hướng (lên/xuống)' };
  }
  if (/\bcho\b/.test(n) && /\b(hien|xuat hien|hien ra)\b/.test(n)) {
    if (!qs.length) return { skip: 'chờ hiện nhưng không có "nhãn"' };
    const timeout = isSlow(o, ctx.title) ? SLOW_TIMEOUT : DEFAULT_TIMEOUT;
    return { kind: 'wait', lines: [`- extendedWaitUntil:\n    visible: ${q(qs[0].v)}\n    timeout: ${timeout}`] };
  }
  if (/^(bam|nhan|cham|tap|click|chon)\b/.test(n) || /\b(bam|nhan|cham|chon)\b/.test(n)) {
    if (!qs.length) return { skip: 'bấm/chọn nhưng không có "nhãn" trong ngoặc kép' };
    return { kind: 'tap', lines: [tapCmd(qs[0].v).y] };
  }
  return { skip: `không map được: "${o}"` };
}

function loginYaml(ctx, role) {
  return `- runFlow:\n    file: ${ctx.sub('login-as-role.yaml')}\n    env:\n      ROLE: ${q(role)}`;
}

export function mapExpected(text) {
  const lines = []; const notes = []; let asserts = 0;
  for (const c of clauses(text)) {
    const n = fold(c); const qs = quoted(c);
    if (qs.length && /\bkhong\b.*\bhien\b|\bkhong\b.*\bxuat hien\b|\bbien mat\b/.test(n)) {
      lines.push(`- assertNotVisible: ${q(qs[0].v)}`); asserts += 1;
    } else if (qs.length && /\bhien( thi| ra)?\b|\bxuat hien\b/.test(n)) {
      lines.push(`- assertVisible: ${q(qs[0].v)}`); asserts += 1;
    } else {
      notes.push(`# [chưa tự kiểm] Expected: ${c.replace(/\n/g, ' ')}`);
    }
  }
  return { lines: [...lines, ...notes], asserts };
}

// ---------------------------------------------------------------- 1 test case -> flow
export function readiness(tc) {
  if (tc.parseErrors?.length) return `lỗi parse: ${tc.parseErrors.join('; ')}`;
  if (!tc.chk) return 'thiếu CHK-ID';
  if (tc.retired) return 'retired';
  if (fold(tc.auto) !== 'yes') return `Auto=${tc.auto || '?'} (không tự động)`;
  const all = [tc.preconditions, ...tc.steps.flatMap((s) => [s.action, s.expected, s.testData])].join('\n');
  if (/\bTBD\b/i.test(all)) return 'có TBD';
  if (/\(\s*dựng\s*:/i.test(tc.preconditions || '')) return 'setup-required (Preconditions "(dựng:…)")';
  if (!tc.steps.length) return 'không có Step';
  return null;
}

export function buildFlow(tc, { subRel }) {
  const why = readiness(tc);
  if (why) return { skip: why };
  const ctx = {
    title: tc.title,
    role: tc.role || (String(tc.preconditions).match(/^\s*ROLE:\s*([\w-]+)/im) || [])[1] || '',
    loggedIn: false,
    sub: (f) => `${subRel}/${f}`,
  };
  const body = []; const kinds = [];
  for (const step of tc.steps) {
    const sect = [`# Bước ${step.n || '?'}${step.action ? ` — ${step.action.replace(/\n/g, ' ')}` : ''}`];
    for (const c of clauses(step.action)) {
      const r = mapAction(c, ctx);
      if (r.skip) return { skip: `bước ${step.n}: ${r.skip}` };
      kinds.push(r.kind); sect.push(...r.lines);
    }
    const ex = mapExpected(step.expected);
    kinds.push(...Array(ex.asserts).fill('assert'));
    sect.push(...ex.lines);
    body.push(...sect);
  }
  if (!kinds.includes('assert')) return { skip: 'không có Expected nào map được thành assertVisible/assertNotVisible' };
  const pre = [];
  if (!kinds.includes('launch') && !kinds.includes('login')) {
    pre.push('- launchApp:\n    permissions:\n      all: allow');
  }
  if (ctx.role && !ctx.loggedIn) pre.push(loginYaml(ctx, ctx.role));
  const frs = String(tc.ref || '').split(/[,\s]+/).filter((x) => /^(FR|BR|NFR|E)-/i.test(x));
  const tags = [tc.chk, ...frs, 'mob'];
  const dataKeys = String(tc.data || '').split(',').map((x) => x.trim()).filter(Boolean);
  const head = [
    GENERATED_MARK,
    'appId: ${APP_ID}',
    `name: ${q(`${tc.chk}: ${tc.title || ''}`)}`,
    'tags:',
    ...tags.map((t) => `  - ${t}`),
    '---',
  ];
  const dataNote = dataKeys.length ? [`# DATA: ${dataKeys.join(', ')} (tiền đề dựng/đọc bởi runner — không hard-code ở flow)`] : [];
  return { yaml: [...head, ...dataNote, ...pre, ...body].join('\n') + '\n', role: ctx.role };
}

// ---------------------------------------------------------------- thư mục / kết quả
function findRoot(dir, explicit) {
  if (explicit) return path.resolve(explicit);
  let d = path.resolve(dir);
  while (true) {
    if (fs.existsSync(path.join(d, 'qa')) || fs.existsSync(path.join(d, '.git'))) return d;
    const up = path.dirname(d);
    if (up === d) return process.cwd();
    d = up;
  }
}

function resultsFile(dir) { return path.join(dir, 'results', 'latest.json'); }
function readResults(dir) {
  if (typeof core.readNormalizedResults === 'function') return core.readNormalizedResults(dir);
  try { const a = JSON.parse(fs.readFileSync(resultsFile(dir), 'utf8')); return Array.isArray(a) ? a : []; } catch { return []; }
}
export function writeResults(dir, entries) {
  // core.writeNormalizedResults: merge theo (chk, target), chuẩn hoá schema/status, sort.
  if (typeof core.writeNormalizedResults === 'function') return core.writeNormalizedResults(dir, entries);
  const cur = readResults(dir);
  for (const e of entries) {
    const i = cur.findIndex((x) => x.chk === e.chk && x.target === e.target);
    if (i >= 0) cur[i] = e; else cur.push(e);
  }
  fs.mkdirSync(path.dirname(resultsFile(dir)), { recursive: true });
  fs.writeFileSync(resultsFile(dir), JSON.stringify(cur, null, 2) + '\n');
  return cur;
}

const ICON = { PASS: '✅ PASS', FAIL_APP: '🔴 FAIL_APP', FAIL_DATA: '🟡 FAIL_DATA', FAIL_OUTDATE: '🟠 FAIL_OUTDATE', FAIL_DOC: '🟣 FAIL_DOC', PENDING: '⏳ PENDING' };
const lastStatus = (dir, chk) => {
  const r = readResults(dir).find((x) => x.chk === chk && x.target === 'mob');
  return r ? ICON[r.status] || r.status : '—';
};

// Lỗi đặc thù Maestro thuộc nhóm nghi-data (đăng nhập, nhập liệu, thiết bị, mở app).
const MAESTRO_DATA_RE = /login|dang nhap|inputtext|unauthor|401|403|no devices|device not found|launchapp|timeout.*dang nhap/;

/** Rớt → status chuẩn hoá. kind: Maestro-data regex → 'data', không thì core.classifyFailure;
 *  core.classifyResult quyết FAIL_DATA / FAIL_DOC (nhãn đáp án tái lập / UC cũ) / FAIL_APP. */
export function classifyFailure(errorText, tc, { oracle, prev = null, fingerprint = '' } = {}) {
  const t = fold(errorText);
  const maestroData = MAESTRO_DATA_RE.test(t);
  if (typeof core.classifyResult === 'function') {
    const kind = maestroData ? 'data' : (typeof core.classifyFailure === 'function' ? core.classifyFailure(errorText) : 'app');
    const orc = oracle !== undefined ? oracle : (typeof core.tcOracle === 'function' ? core.tcOracle(tc, null) : '');
    return core.classifyResult({ status: 'FAIL', kind, oracle: orc, prev, fingerprint }).status;
  }
  if (maestroData) return 'FAIL_DATA';
  const doc = /dap an:\s*(uc cu|tai lap)/.test(fold(tc?.checklist || ''));
  return doc ? 'FAIL_DOC' : 'FAIL_APP';
}

export function parseJunit(xml) {
  const out = [];
  const re = /<testcase\b([^>]*?)(\/>|>([\s\S]*?)<\/testcase>)/g;
  let m;
  while ((m = re.exec(xml))) {
    const name = (m[1].match(/\bname="([^"]*)"/) || [])[1] || '';
    const body = m[3] || '';
    const fail = body.match(/<(failure|error)\b([^>]*?)(?:\/>|>([\s\S]*?)<\/\1>)/);
    const skipped = /<skipped\b/.test(body);
    const msg = fail ? ((fail[2].match(/message="([^"]*)"/) || [])[1] || fail[3] || 'failed') : '';
    out.push({ name, status: fail ? 'FAIL' : skipped ? 'SKIP' : 'PASS', message: msg.replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>') });
  }
  return out;
}

// ---------------------------------------------------------------- gen
function collect(dir, root) {
  const tcDir = path.join(dir, 'testcases');
  if (!fs.existsSync(tcDir)) throw new Error(`Thiếu ${tcDir} — chạy /test-cases trước`);
  const files = fs.readdirSync(tcDir).filter((f) => /^testcases-.*\.md$/i.test(f)).sort();
  if (!files.length) throw new Error(`Không có testcases-*.md trong ${tcDir}`);
  const generated = []; const skipped = [];
  for (const f of files) {
    const scope = f.replace(/^testcases-/i, '').replace(/\.md$/i, '');
    for (const tc of parseTestcases(fs.readFileSync(path.join(tcDir, f), 'utf8'))) {
      if (tc.target !== 'mob') continue;
      const flowDir = path.join(dir, 'mobile', 'maestro', 'flows', scope);
      const subRel = path.relative(flowDir, path.join(root, SUBFLOW_DIR)).split(path.sep).join('/');
      const r = buildFlow(tc, { subRel });
      const chk = tc.chk || `TC-${tc.stt || '?'}`;
      if (r.skip) skipped.push({ scope, chk, reason: r.skip });
      else generated.push({ scope, chk, title: tc.title, tc, yaml: r.yaml, file: path.join(flowDir, `${chk.toLowerCase()}.yaml`) });
    }
  }
  return { generated, skipped };
}

function writeIndex(dir, feature, rep) {
  const scopes = [...new Set(rep.generated.map((g) => g.scope))];
  const L = [
    '---', 'type: test-index', `feature: ${feature}`, 'status: draft', `updated: ${new Date().toISOString().slice(0, 10)}`, 'links: []', '---', '',
    `# ${feature} — Maestro (mobile) index`, '',
    '> Sinh bởi `.claude/scripts/maestro-gen.mjs` — không sửa tay.', '',
    '## Theo scope', '', '| Scope | File | Tests | Kết quả gần nhất |', '|---|---|---|---|',
  ];
  for (const s of scopes) {
    const items = rep.generated.filter((g) => g.scope === s);
    const stat = {};
    for (const g of items) { const k = lastStatus(dir, g.chk); stat[k] = (stat[k] || 0) + 1; }
    L.push(`| ${s} | \`mobile/maestro/flows/${s}/\` | ${items.length} | ${Object.entries(stat).map(([k, v]) => `${k} ×${v}`).join(' · ')} |`);
  }
  if (!scopes.length) L.push('| — | — | 0 | — |');
  L.push('', '## Theo CHK', '', '| CHK-ID | Flow | Codegen | Kết quả gần nhất |', '|---|---|---|---|');
  for (const g of rep.generated) L.push(`| ${g.chk} | \`flows/${g.scope}/${g.chk.toLowerCase()}.yaml\` | ✅ sinh | ${lastStatus(dir, g.chk)} |`);
  if (!rep.generated.length) L.push('| — | — | — | — |');
  L.push('', '## Skipped', '', '| CHK-ID | Lý do |', '|---|---|');
  for (const s of rep.skipped) L.push(`| ${s.chk} | ${String(s.reason).replace(/\|/g, '\\|')} |`);
  if (!rep.skipped.length) L.push('| — | — |');
  const out = path.join(dir, 'mobile', `${feature}-mobile-index.md`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, L.join('\n') + '\n');
  return out;
}

function gen(o) {
  const dir = path.resolve(o.dir);
  const feature = path.basename(path.dirname(dir));
  const root = findRoot(dir, o.root);
  const rep = collect(dir, root);
  const msg = `${rep.generated.length} flow, skip ${rep.skipped.length}`;
  if (o.dryRun) {
    console.log(`[maestro-gen] dry-run: ${msg}`);
    for (const g of rep.generated) console.log(`  + flows/${g.scope}/${g.chk.toLowerCase()}.yaml`);
    for (const s of rep.skipped) console.log(`  - ${s.chk}: ${s.reason}`);
    return rep;
  }
  const flowsRoot = path.join(dir, 'mobile', 'maestro', 'flows');
  if (fs.existsSync(flowsRoot)) { // xoá flow cũ do máy sinh (có dấu hiệu), giữ file tay
    const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.yaml') && fs.readFileSync(p, 'utf8').startsWith(GENERATED_MARK)) fs.rmSync(p);
    } };
    walk(flowsRoot);
  }
  for (const g of rep.generated) { fs.mkdirSync(path.dirname(g.file), { recursive: true }); fs.writeFileSync(g.file, g.yaml); }
  const cfg = path.join(dir, 'mobile', 'maestro', 'config.yaml');
  fs.mkdirSync(path.dirname(cfg), { recursive: true });
  fs.writeFileSync(cfg, `${GENERATED_MARK}\n# Chạy: maestro test -e APP_ID=<bundle id> --config config.yaml flows/   (APP_ID iOS UAT: innvie.delta.app.uat)\nflows:\n  - "flows/**"\n`);
  const idx = writeIndex(dir, feature, rep);
  console.log(`[maestro-gen] gen: ${msg}\n  index: ${path.relative(process.cwd(), idx)}`);
  return rep;
}

// ---------------------------------------------------------------- run
function maestroBin() {
  const bin = process.env.MAESTRO_BIN || 'maestro';
  const r = spawnSync(bin, ['--version'], { encoding: 'utf8' });
  return r.error || r.status !== 0 ? null : bin;
}

// qa/.env: KEY=VALUE đơn giản, bỏ comment/dòng trống. Không in giá trị.
export function parseDotenv(text) {
  const out = {};
  for (const line of String(text).split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith('#')) continue;
    let v = m[2];
    if (/^(['"]).*\1$/.test(v)) v = v.slice(1, -1);
    out[m[1]] = v;
  }
  return out;
}

// Gom tên ${NAME} trong flow + subflow nó gọi (qua `file:`), chỉ lấy tên đơn giản.
export function referencedVars(flowFile, root) {
  const seen = new Set(); const names = new Set();
  const visit = (f) => {
    if (seen.has(f) || !fs.existsSync(f)) return;
    seen.add(f);
    const txt = fs.readFileSync(f, 'utf8');
    for (const m of txt.matchAll(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g)) names.add(m[1]);
    for (const m of txt.matchAll(/^\s*file:\s*["']?([^\s"']+)["']?\s*$/gm)) {
      for (const base of [path.dirname(f), root, path.join(root, SUBFLOW_DIR)]) {
        const c = path.resolve(base, m[1]);
        if (fs.existsSync(c)) { visit(c); break; }
      }
    }
  };
  visit(flowFile);
  return [...names];
}

export function buildEnvArgs(names, vars) {
  const keys = new Set(['APP_ID', ...Object.keys(vars).filter((k) => k.startsWith('QA_')), ...names]);
  const args = [];
  for (const k of keys) if (vars[k] !== undefined && vars[k] !== '') args.push('-e', `${k}=${vars[k]}`);
  return args;
}

function run(o) {
  const dir = path.resolve(o.dir);
  const feature = path.basename(path.dirname(dir));
  const root = findRoot(dir, o.root);
  const envFile = path.join(root, 'qa', '.env');
  const dotenv = fs.existsSync(envFile) ? parseDotenv(fs.readFileSync(envFile, 'utf8')) : {};
  const vars = { ...dotenv, ...Object.fromEntries(Object.entries(process.env).filter(([k]) => k === 'APP_ID' || k.startsWith('QA_'))) };
  const envName = String(o.env || vars.QA_ENV || 'dev').toLowerCase();
  if (['prod', 'production'].includes(envName)) throw new Error('từ chối chạy trên prod (QA_ENV/--env = prod)');
  const rep = collect(dir, root);
  let items = rep.generated;
  if (o.tc) items = items.filter((g) => g.chk.toLowerCase() === o.tc.toLowerCase());
  if (o.dryRun) { console.log(`[maestro-gen] dry-run run: ${items.length} flow`); return []; }
  gen({ ...o, dryRun: false }); // bảo đảm flow là bản mới
  const env = o.env || vars.QA_ENV || 'dev';
  const build = o.build || process.env.QA_BUILD || '';
  const at = new Date().toISOString();
  const bin = maestroBin();
  const results = [];
  const checklistIndex = typeof core.loadChecklistIndex === 'function' ? core.loadChecklistIndex(dir) : null;
  const oracleOf = (tc) => (typeof core.tcOracle === 'function' ? core.tcOracle(tc, checklistIndex) : undefined);
  const outDir = path.join(dir, 'results');
  fs.mkdirSync(outDir, { recursive: true });
  for (const g of items) {
    if (!bin) { results.push({ chk: g.chk, target: 'mob', status: 'PENDING', env, build, at, note: 'maestro chưa cài' }); continue; }
    const xml = path.join(outDir, `maestro-${g.chk.toLowerCase()}.xml`);
    const r = spawnSync(bin, ['test', ...buildEnvArgs(referencedVars(g.file, root), vars), g.file, '--format', 'junit', '--output', xml], { encoding: 'utf8', cwd: path.join(dir, 'mobile', 'maestro') });
    let cases = [];
    try { cases = parseJunit(fs.readFileSync(xml, 'utf8')); } catch { /* không có junit */ }
    const bad = cases.find((c) => c.status === 'FAIL');
    if (bad) {
      results.push({ chk: g.chk, target: 'mob', status: classifyFailure(`${bad.message}`, g.tc, { oracle: oracleOf(g.tc) }), env, build, at, note: clean(bad.message).slice(0, 300) });
    } else if (cases.length && r.status === 0) {
      results.push({ chk: g.chk, target: 'mob', status: 'PASS', env, build, at, note: '' });
    } else {
      const err = clean(`${r.stderr || ''} ${r.stdout || ''}`).slice(-300) || `maestro thoát mã ${r.status}`;
      results.push({ chk: g.chk, target: 'mob', status: classifyFailure(err, g.tc, { oracle: oracleOf(g.tc) }), env, build, at, note: err });
    }
  }
  writeResults(dir, results);
  writeIndex(dir, feature, rep);
  const tally = results.reduce((a, r) => ({ ...a, [r.status]: (a[r.status] || 0) + 1 }), {});
  console.log(`[maestro-gen] run: ${JSON.stringify(tally)}${bin ? '' : ' (maestro chưa cài → PENDING)'}`);
  return results;
}

// ---------------------------------------------------------------- CLI
const isMain = process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname;
if (isMain) {
  const o = parseArgs(process.argv.slice(2));
  try {
    if (!o.dir || !['gen', 'run'].includes(o.cmd)) {
      console.error('Dùng: maestro-gen.mjs gen|run --dir docs/{feature}/test [--tc CHK-..] [--dry-run] [--root <repo>] [--env dev] [--build x]');
      process.exit(2);
    }
    if (o.cmd === 'gen') gen(o); else run(o);
  } catch (e) { console.error(`[maestro-gen] ${e.message}`); process.exit(1); }
}
