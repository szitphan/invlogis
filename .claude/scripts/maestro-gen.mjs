const HERE = path.dirname(new URL(import.meta.url).pathname);
const GENERATED_MARK = '# AUTO-GENERATED by maestro-gen — KHÔNG sửa tay, sinh lại từ testcases-*.md';
const SUBFLOW_DIR = 'qa/mobile/subflows';
const DEFAULT_TIMEOUT = 30000;
const SLOW_TIMEOUT = 25000; // theo brief: 25000 cho trạng thái iGAS/SignalR
const FIELD_RE = /^\s*\*\*(STT|Category|Sub-Category|Checklist|Ref|Priority|Title|Description|Auto|Target|Role|Data|Preconditions|Step|Action|Expected|Test Data):\*\*\s*(.*)$/i;
const CHK_RE = /\bCHK-[a-z0-9][a-z0-9-]*-\d{3,}\b/i;

